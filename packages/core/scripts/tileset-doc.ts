/**
 * Writes apps/game/TILESET.md from the tile registry (src/local/tiles.ts): every tile the local
 * map can place, what it does in play and what its art should show, with the tileset format.
 *
 *   npm run tileset:doc
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DECOR, GROUND_TILES, OBJECT_TILES, type TileDef } from '../src/local/tiles';

const out = fileURLToPath(new URL('../../../apps/game/TILESET.md', import.meta.url));

const SECTIONS: { title: string; layer: 'ground' | 'object'; test: (d: TileDef) => boolean; note: string }[] = [
  { title: 'Ground: natural', layer: 'ground', test: (d) => !d.water && !/^(road|track|path|cobbles|flagstones|lawn|garden_bed|field|vineyard|yard|grave_ground|planks|bridge|ditch|mound|spoil|floor_)/.test(d.name), note: 'Fills the whole tile. Variants are picked at random per position, so they should tile with each other seamlessly.' },
  { title: 'Ground: water', layer: 'ground', test: (d) => !!d.water, note: 'Water joins other water (mask4): draw the 16 frames with a shore edge on each side that is not water.' },
  { title: 'Ground: made outdoors', layer: 'ground', test: (d) => /^(road|track|path|cobbles|flagstones|lawn|garden_bed|field|vineyard|yard|grave_ground|planks|bridge|ditch|mound|spoil)/.test(d.name), note: 'Roads, streets, squares, fields and yards, from the town and village plans.' },
  { title: 'Ground: floors indoors', layer: 'ground', test: (d) => d.name.startsWith('floor_'), note: 'The ground floor of every building, by the floor plan\'s surface.' },
  { title: 'Walls, doors and windows', layer: 'object', test: (d) => d.group === 'wall' || d.group === 'townwall' || d.group === 'palisade', note: 'All in a join group: draw 16 frames each (see below). Doors and windows sit in a wall line, so they join the walls either side.' },
  { title: 'Stairs and ways down', layer: 'object', test: (d) => /stairs|ladder|entrance|cave_mouth/.test(d.name), note: 'Drawn over the floor or ground (transparent background).' },
  { title: 'Plants and trees', layer: 'object', test: (d) => /^(tree_|great_trunk|bush|scrub|tall_grass|ferns|reeds|flowers|cactus|mushrooms|crops|vines|hedge)/.test(d.name), note: 'Over the ground, transparent background. Trees fill most of the tile (a crown seen from above with the trunk showing at the foot).' },
  { title: 'Stones, earthworks and town things', layer: 'object', test: (d) => /^(boulder|stones|menhir|totem|pyramid|rubble|ruin_wall|fence|well|fountain|grave|tomb|stall|tent|wagon|boat|horse|campfire|woodpile|millwheel|signpost)$/.test(d.name), note: 'Over the ground, transparent background.' },
  { title: 'Furniture', layer: 'object', test: () => true, note: 'From the floor plans. Over the floor, transparent background, seen from slightly above. Long pieces (beds, tables, pews) repeat along two or more tiles, so their ends should meet cleanly.' },
];

const flags = (d: TileDef) => [d.pass ? 'walk' : 'blocks', d.opaque ? 'hides' : '', d.water ? `${d.water} water` : '', d.toggle ? `opens: ${d.toggle}` : ''].filter(Boolean).join(', ');

let md = `# Tileset

The tiles the game draws, generated from the tile registry (\`packages/core/src/local/tiles.ts\`)
by \`npm run tileset:doc\`. Do not edit this file by hand: change the registry and run the script.

## Format

- **Tile size.** A tile is 1.5 m of ground (one cell of the floor plans): about a person's
  stride and a half. Art is **16 × 16 pixels**, drawn **top-down** (see
  \`docs/design/navigation.md\`, *How the local map is drawn*). The game shows it at 2× by default
  (+ and - zoom from 1× to 4×).
- **Layers.** Each position has a **ground** tile (fills the whole square); sometimes an **object**
  on top of it (wall, door, tree, bed), drawn with a transparent background; and, on open ground
  with no object, sometimes a **decoration** (a tuft of grass, pebbles), drawn only and placed by
  position (see *Decorations* below).
- **Files.** Put the sheets and their index in \`apps/game/public/tileset/\`:
  - one or more sheets (PNG), any number of 16 × 16 cells in a grid;
  - \`tileset.json\`, the index:

\`\`\`json
{
  "tileSize": 16,
  "image": "tileset.png",
  "sheets": { "nature": "nature.png", "water": "water.png" },
  "tiles": {
    "grass": [0, 0],
    "grass.1": [1, 0],
    "wall_stone#5": [5, 3],
    "tree_broadleaf": { "sheet": "nature", "at": [2, 0], "size": [1, 2] },
    "boulder": { "sheet": "nature", "rect": [0, 64, 18, 18], "offset": [-1, -2] },
    "water_shallow#15": { "sheet": "water", "at": [0, 0], "frames": 4, "ms": 180 },
    "campfire": { "at": [[0, 5], [1, 5], [2, 5]], "ms": 120 },
    "pebbles": { "sheet": "nature", "at": [6, 6] }
  },
  "standIns": {
    "grass_lush": "grass",
    "needle_floor": { "as": "forest_floor", "tint": "#e8dcc4" }
  }
}
\`\`\`

- **A frame** is given as \`[column, row]\` on the default sheet (\`image\`), or as an object:
  - \`"sheet"\`: a sheet named in \`sheets\` (the default sheet if left out);
  - \`"at": [column, row]\` with \`"size": [w, h]\` in cells (1 × 1 if left out), or \`"rect": [x, y, w, h]\`
    in pixels;
  - \`"offset": [dx, dy]\`: where the picture's top-left corner sits from the tile's, in pixels. If
    left out, a picture larger than a tile **stands on the tile**: centred across it, its foot on
    the tile's foot, rising above it. Keep this to a few pixels (a person's head, the top of a
    barrel): the map is top-down;
  - **animation:** \`"frames": n\` (laid out to the right, or along \`"step": [dx, dy]\` in cells) or
    \`"at"\` as a list of cells; each shown \`"ms"\` milliseconds (200 if left out).
- **Frame names.** The tile's name (\`grass\`); numbered variants after a dot (\`grass.1\`,
  \`grass.2\`), picked at random by position; and join frames after a hash (\`wall_stone#5\`).
- **Joins (mask4).** Tiles marked *join* connect to neighbours of the same group (all walls,
  doors and windows are one group; water is another). Their frame number is the sum of the
  sides that join: **north 1, east 2, south 4, west 8** (0 to 15). A join tile drawn only as its
  plain name is used for every side.
- **Stand-ins.** A tile with no art of its own can borrow another's (every variant and join of it),
  multiplied by a \`tint\` if one is given, until it has art: \`"grass_lush": "grass"\`.
- **Anything missing** is drawn as a placeholder (its colour and glyph below), so art can be
  added a few tiles at a time and the game always runs. Mistakes in \`tileset.json\` are listed in
  the developer console and the rest is used.

Suggested sheet layout: one row per section below, in this order, with the 16 join frames of a
tile in a row of their own; animations along a row.
`;

const used = new Set<string>();
for (const s of SECTIONS) {
  const list = (s.layer === 'ground' ? GROUND_TILES : OBJECT_TILES).filter((d) => d.name !== 'void' && d.name !== 'none' && !used.has(`${d.layer}:${d.name}`) && s.test(d));
  if (!list.length) continue;
  md += `## ${s.title}\n\n${s.note}\n\n| Tile | Draw | In play | Frames | Placeholder |\n|---|---|---|---|---|\n`;
  for (const d of list) {
    used.add(`${d.layer}:${d.name}`);
    const frames = d.join === 'mask4' ? `join (16), group ${d.group}` : (d.variants ?? 1) > 1 ? `${d.variants} variants` : '1';
    md += `| \`${d.name}\` | ${d.art} | ${flags(d)} | ${frames} | ${d.glyph ? `\`${d.glyph === '|' ? '\\|' : d.glyph}\` ` : ''}${d.colour} |\n`;
  }
  md += '\n';
}
md += `## Decorations\n\nSmall things scattered over open ground with no object on it, drawn only: they block nothing and are not saved. Where one lies is worked out from the position, so each lies on about the share of its ground given here; seasonal ones leave their tiles bare out of season. Transparent background; keep them small and low, so that the ground still reads.\n\n| Decoration | Draw | Lies on | Share | Seasons | Frames | Placeholder |\n|---|---|---|---|---|---|---|\n`;
for (const d of DECOR) md += `| \`${d.name}\` | ${d.art} | ${d.on.map((n) => `\`${n}\``).join(', ')} | ${Math.round(d.chance * 100)}% | ${d.seasons?.join(', ') ?? 'all year'} | ${(d.variants ?? 1) > 1 ? `${d.variants} variants` : '1'} | ${d.colour} |\n`;
md += '\n';
const nG = GROUND_TILES.length - 1, nO = OBJECT_TILES.length - 1;
const frames = [...GROUND_TILES, ...OBJECT_TILES].filter((d) => d.name !== 'void' && d.name !== 'none').reduce((n, d) => n + (d.join === 'mask4' ? 16 : d.variants ?? 1), 0) + DECOR.reduce((n, d) => n + (d.variants ?? 1), 0);
md += `## Totals\n\n${nG} ground tiles, ${nO} objects and ${DECOR.length} decorations: ${frames} frames in all with every variant and join drawn.\n`;
writeFileSync(out, md);
console.log(`Wrote ${out}: ${nG} ground tiles, ${nO} objects, ${DECOR.length} decorations, ${frames} frames.`);
